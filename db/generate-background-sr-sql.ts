/**
 * Offline generator: writes db/migrations/0090_background_sr_v2.sql
 * Never connects to the database.
 *
 * Run: npx tsx db/generate-background-sr-sql.ts
 */

import { writeFileSync } from "node:fs"
import { resolve } from "node:path"

import {
  BACKGROUND_SR_ASSESSMENT_CODE,
  BACKGROUND_SR_ASSESSMENT_NAME,
  BACKGROUND_SR_CLIENT_DISPLAY_NAME,
  BACKGROUND_SR_ELEMENTS,
} from "../lib/assessments/definitions/background-sr"

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

function sqlNullableString(value: string | null | undefined): string {
  return value == null ? "NULL" : sqlString(value)
}

function sqlShowWhen(showWhen: { key: string; in: string[] } | null): string {
  if (!showWhen) return "NULL"
  return `${sqlString(JSON.stringify({ key: showWhen.key, in: showWhen.in }))}::jsonb`
}

function sqlListConfig(config: unknown): string {
  if (config == null) return "NULL"
  return `${sqlString(JSON.stringify(config))}::jsonb`
}

const code = sqlString(BACKGROUND_SR_ASSESSMENT_CODE)
const lines: string[] = []

lines.push(`-- Round AY: BACKGROUND_SR v2 shared-form elements.`)
lines.push(`-- Generated by db/generate-background-sr-sql.ts — do not connect to a database.`)
lines.push(`-- Elements: ${BACKGROUND_SR_ELEMENTS.length}`)
lines.push(`-- Idempotent where practical: deletes old template elements/options, then inserts.`)
lines.push(``)
lines.push(`BEGIN;`)
lines.push(``)

lines.push(`-- Ensure the definition exists and is client-completable.`)
lines.push(`INSERT INTO assessment_definitions (`)
lines.push(`  assessment_code,`)
lines.push(`  assessment_name,`)
lines.push(`  client_display_name,`)
lines.push(`  assessment_type,`)
lines.push(`  scoring_enabled,`)
lines.push(`  client_completable,`)
lines.push(`  practitioner_completable,`)
lines.push(`  is_active`)
lines.push(`) VALUES (`)
lines.push(`  ${code},`)
lines.push(`  ${sqlString(BACKGROUND_SR_ASSESSMENT_NAME)},`)
lines.push(`  ${sqlString(BACKGROUND_SR_CLIENT_DISPLAY_NAME)},`)
lines.push(`  'client_self_report',`)
lines.push(`  false,`)
lines.push(`  true,`)
lines.push(`  false,`)
lines.push(`  true`)
lines.push(`)`)
lines.push(`ON CONFLICT (assessment_code) DO UPDATE SET`)
lines.push(`  assessment_name = EXCLUDED.assessment_name,`)
lines.push(`  client_display_name = EXCLUDED.client_display_name,`)
lines.push(`  assessment_type = EXCLUDED.assessment_type,`)
lines.push(`  scoring_enabled = EXCLUDED.scoring_enabled,`)
lines.push(`  client_completable = EXCLUDED.client_completable,`)
lines.push(`  practitioner_completable = EXCLUDED.practitioner_completable,`)
lines.push(`  is_active = EXCLUDED.is_active,`)
lines.push(`  updated_at = NOW();`)
lines.push(``)

lines.push(`-- Drop old template options / responses / elements (v1 had no shared-form rows; ignore old results).`)
lines.push(`DELETE FROM assessment_responses r`)
lines.push(`USING assessment_elements e, assessment_definitions d`)
lines.push(`WHERE r.assessment_element_id = e.assessment_element_id`)
lines.push(`  AND e.assessment_definition_id = d.assessment_definition_id`)
lines.push(`  AND d.assessment_code = ${code}`)
lines.push(`  AND e.assessment_instance_id IS NULL;`)
lines.push(``)

lines.push(`DELETE FROM assessment_options o`)
lines.push(`USING assessment_elements e, assessment_definitions d`)
lines.push(`WHERE o.assessment_element_id = e.assessment_element_id`)
lines.push(`  AND e.assessment_definition_id = d.assessment_definition_id`)
lines.push(`  AND d.assessment_code = ${code}`)
lines.push(`  AND e.assessment_instance_id IS NULL;`)
lines.push(``)

lines.push(`DELETE FROM assessment_elements e`)
lines.push(`USING assessment_definitions d`)
lines.push(`WHERE e.assessment_definition_id = d.assessment_definition_id`)
lines.push(`  AND d.assessment_code = ${code}`)
lines.push(`  AND e.assessment_instance_id IS NULL;`)
lines.push(``)

for (const element of BACKGROUND_SR_ELEMENTS) {
  lines.push(`INSERT INTO assessment_elements (`)
  lines.push(`  assessment_definition_id,`)
  lines.push(`  element_key,`)
  lines.push(`  question_text,`)
  lines.push(`  element_type,`)
  lines.push(`  data_type,`)
  lines.push(`  display_order,`)
  lines.push(`  is_required,`)
  lines.push(`  is_active,`)
  lines.push(`  group_label,`)
  lines.push(`  subgroup_label,`)
  lines.push(`  parent_element_key,`)
  lines.push(`  show_when_json,`)
  lines.push(`  required_group_key,`)
  lines.push(`  help_text,`)
  lines.push(`  allow_in_person,`)
  lines.push(`  list_config_json`)
  lines.push(`)`)
  lines.push(`SELECT`)
  lines.push(`  d.assessment_definition_id,`)
  lines.push(`  ${sqlString(element.elementKey)},`)
  lines.push(`  ${sqlString(element.questionText)},`)
  lines.push(`  ${sqlString(element.elementType)},`)
  lines.push(`  'text',`)
  lines.push(`  ${element.displayOrder},`)
  lines.push(`  ${element.isRequired},`)
  lines.push(`  true,`)
  lines.push(`  ${sqlNullableString(element.groupLabel)},`)
  lines.push(`  ${sqlNullableString(element.subgroupLabel)},`)
  lines.push(`  ${sqlNullableString(element.parentElementKey)},`)
  lines.push(`  ${sqlShowWhen(element.showWhen)},`)
  lines.push(`  ${sqlNullableString(element.requiredGroupKey)},`)
  lines.push(`  ${sqlNullableString(element.helpText)},`)
  lines.push(`  ${element.allowInPerson === true},`)
  lines.push(`  ${sqlListConfig(element.listConfig ?? null)}`)
  lines.push(`FROM assessment_definitions d`)
  lines.push(`WHERE d.assessment_code = ${code}`)
  lines.push(`ON CONFLICT (element_key) DO UPDATE SET`)
  lines.push(`  assessment_definition_id = EXCLUDED.assessment_definition_id,`)
  lines.push(`  question_text = EXCLUDED.question_text,`)
  lines.push(`  element_type = EXCLUDED.element_type,`)
  lines.push(`  data_type = EXCLUDED.data_type,`)
  lines.push(`  display_order = EXCLUDED.display_order,`)
  lines.push(`  is_required = EXCLUDED.is_required,`)
  lines.push(`  is_active = EXCLUDED.is_active,`)
  lines.push(`  group_label = EXCLUDED.group_label,`)
  lines.push(`  subgroup_label = EXCLUDED.subgroup_label,`)
  lines.push(`  parent_element_key = EXCLUDED.parent_element_key,`)
  lines.push(`  show_when_json = EXCLUDED.show_when_json,`)
  lines.push(`  required_group_key = EXCLUDED.required_group_key,`)
  lines.push(`  help_text = EXCLUDED.help_text,`)
  lines.push(`  allow_in_person = EXCLUDED.allow_in_person,`)
  lines.push(`  list_config_json = EXCLUDED.list_config_json;`)
  lines.push(``)

  for (const option of element.options) {
    lines.push(`INSERT INTO assessment_options (`)
    lines.push(`  assessment_element_id,`)
    lines.push(`  assessment_definition_id,`)
    lines.push(`  option_label,`)
    lines.push(`  option_value,`)
    lines.push(`  score_value,`)
    lines.push(`  display_order`)
    lines.push(`)`)
    lines.push(`SELECT`)
    lines.push(`  e.assessment_element_id,`)
    lines.push(`  d.assessment_definition_id,`)
    lines.push(`  ${sqlString(option.label)},`)
    lines.push(`  ${sqlString(option.value)},`)
    lines.push(`  ${option.scoreValue ?? 0},`)
    lines.push(`  ${option.displayOrder}`)
    lines.push(`FROM assessment_elements e`)
    lines.push(`JOIN assessment_definitions d`)
    lines.push(`  ON d.assessment_definition_id = e.assessment_definition_id`)
    lines.push(`WHERE e.element_key = ${sqlString(element.elementKey)}`)
    lines.push(`  AND d.assessment_code = ${code}`)
    lines.push(`  AND NOT EXISTS (`)
    lines.push(`    SELECT 1`)
    lines.push(`    FROM assessment_options o`)
    lines.push(`    WHERE o.assessment_element_id = e.assessment_element_id`)
    lines.push(`      AND o.option_value = ${sqlString(option.value)}`)
    lines.push(`  );`)
    lines.push(``)
  }
}

lines.push(`COMMIT;`)
lines.push(``)

const out = resolve(process.cwd(), "db/migrations/0090_background_sr_v2.sql")
writeFileSync(out, lines.join("\n"), "utf8")
console.log(`Wrote ${out} (${BACKGROUND_SR_ELEMENTS.length} elements)`)
